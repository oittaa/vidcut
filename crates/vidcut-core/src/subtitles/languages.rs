pub fn three_letter(language: &str, terminology: bool) -> Option<String> {
    let primary = language
        .split(['-', '_'])
        .next()
        .unwrap_or_default()
        .to_ascii_lowercase();
    let pick = |c: &(&str, &'static str, &'static str)| if terminology { c.2 } else { c.1 };
    match primary.len() {
        2 => CODES
            .iter()
            .find(|(one, _, _)| *one == primary)
            .map(pick)
            .map(String::from),
        3 if primary.chars().all(|c| c.is_ascii_lowercase()) => Some(
            CODES
                .iter()
                .find(|(_, b, t)| *b == primary || *t == primary)
                .map_or(primary.clone(), |c| pick(c).to_string()),
        ),
        _ => None,
    }
}
